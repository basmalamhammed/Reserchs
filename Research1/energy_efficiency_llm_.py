# ============================================================

def effective_inference_throughput_proxy(
    flops_per_token,
    tokens_per_second,
):
    """
    Estimate effective inference compute throughput.

    flops_per_token:
        Approximate FLOPs required per generated token.

    tokens_per_second:
        Measured generation throughput.

    Returns:
        Effective FLOPs/s.
    """

    return float(
        flops_per_token
        * tokens_per_second
    )

