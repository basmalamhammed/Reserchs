from dataclasses import dataclass, asdict

@dataclass
class RunResult:
    config_name: str
    total_joules: float
    total_facility_joules_est: float
    request_latency_s: float
    avg_device_power_w: float
    avg_gpu_utilization_pct: float
    num_input_tokens: int
    num_output_tokens: int
    batch_size: int
    peak_memory_mb: float
    n_power_samples: int


def measure_single_run(model, tokenizer, input_ids, config_name,
                        max_new_tokens=100, batch_size=1, pue=1.10):
    input_ids_batched = input_ids.repeat(batch_size, 1)
    attn_mask = torch.ones_like(input_ids_batched)
    pad_id = tokenizer.pad_token_id or tokenizer.eos_token_id
    input_len = input_ids_batched.shape[1]

    torch.cuda.reset_peak_memory_stats()
    torch.cuda.synchronize()
    mon = SystemMonitor(_handle, pue=pue, sample_interval_s=0.005)
    with mon:
        with torch.no_grad():
            output = model.generate(
                input_ids=input_ids_batched, attention_mask=attn_mask,
                max_new_tokens=max_new_tokens, do_sample=False, pad_token_id=pad_id,
            )
        torch.cuda.synchronize()
    m = mon.results()

    peak_mem_mb = torch.cuda.max_memory_allocated() / (1024 ** 2)
    total_output_len = output.shape[1] - input_len
    num_output_tokens = total_output_len * batch_size

    return RunResult(
        config_name=config_name,
        total_joules=m["device_joules"],
        total_facility_joules_est=m["facility_joules_estimate"],
        request_latency_s=m["duration_s"],
        avg_device_power_w=m["avg_device_power_w"],
        avg_gpu_utilization_pct=m["avg_gpu_utilization_pct"],
        num_input_tokens=input_len * batch_size,
        num_output_tokens=num_output_tokens,
        batch_size=batch_size,
        peak_memory_mb=peak_mem_mb,
        n_power_samples=m["n_samples"],
    )

