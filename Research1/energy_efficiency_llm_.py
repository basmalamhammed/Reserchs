PUE_SWEEP = [
    1.1,
    1.2,
    1.4,
    1.6,
]


def run_with_repeats(
    model,
    tokenizer,
    input_ids,
    config_name,
    n_repeats=8,
    max_new_tokens=100,
    batch_size=1,
    pue=1.10,
    warmup_runs=2,
):

    # --------------------------------------------------------
    # Warmup
    # --------------------------------------------------------

    print(
        f"  Warmup: {warmup_runs} run(s)..."
    )

    for _ in range(warmup_runs):

        measure_single_run(

            model,
            tokenizer,
            input_ids,
            config_name,

            max_new_tokens=max_new_tokens,
            batch_size=batch_size,
            pue=pue,
        )

    rows = []

    # --------------------------------------------------------
    # Real measurements
    # --------------------------------------------------------

    for i in range(n_repeats):

        result = measure_single_run(

            model,
            tokenizer,
            input_ids,
            config_name,

            max_new_tokens=max_new_tokens,
            batch_size=batch_size,
            pue=pue,
        )

        d = asdict(result)

        # ----------------------------------------------------
        # PRIMARY METRIC
        # ----------------------------------------------------

        d["etok_total_j"] = (
            result.total_joules
            / result.num_output_tokens
        )

        # ----------------------------------------------------
        # Throughput
        # ----------------------------------------------------

        d["tokens_per_s"] = (
            result.num_output_tokens
            / result.request_latency_s
        )

        # ----------------------------------------------------
        # PUE sensitivity
        # ----------------------------------------------------

        for p in PUE_SWEEP:

            d[
                f"etok_total_facility_pue{p}"
            ] = (
                result.total_joules * p
            ) / result.num_output_tokens

        rows.append(d)

        print(
            f"  [{config_name}] "
            f"run {i+1}/{n_repeats}: "
            f"etok={d['etok_total_j']:.4f} J/tok | "
            f"tok/s={d['tokens_per_s']:.2f} | "
            f"power={d['avg_device_power_w']:.1f} W | "
            f"samples={d['n_power_samples']} | "
            f"mem={d['peak_memory_mb']:.0f} MB"
        )

    df = pd.DataFrame(rows)

    # --------------------------------------------------------
    # Outlier detection
    # --------------------------------------------------------

    median_energy = df[
        "etok_total_j"
    ].median()

    mad = (
        df["etok_total_j"]
        - median_energy
    ).abs().median()

    if mad > 0:

        df["is_outlier"] = (
            (
                df["etok_total_j"]
                - median_energy
            ).abs()
            > 3 * mad
        )

    else:

        df["is_outlier"] = False

    if df["is_outlier"].any():

        print(
            f"  WARNING: "
            f"{df['is_outlier'].sum()} "
            "outlier run(s) detected."
        )

    return df


def bootstrap_ci_median(
    values,
    n_boot=2000,
    ci=0.95,
    seed=0,
):

    rng = np.random.default_rng(
        seed
    )

    boot_medians = np.array([

        np.median(
            rng.choice(
                values,
                size=len(values),
                replace=True
            )
        )

        for _ in range(n_boot)

    ])

    alpha = 1 - ci

    lo, hi = np.percentile(
        boot_medians,
        [
            100 * alpha / 2,
            100 * (1 - alpha / 2)
        ]
    )

    return float(lo), float(hi)


def summarize(df):

    clean = df[
        ~df["is_outlier"]
    ].copy()

    if len(clean) == 0:

        raise RuntimeError(
            "All measurements were flagged as outliers."
        )

    energy = clean[
        "etok_total_j"
    ].values

    # Mean confidence interval
    if len(energy) > 1:

        ci_t = scipy_stats.t.interval(
            0.95,
            len(energy) - 1,
            loc=energy.mean(),
            scale=scipy_stats.sem(energy),
        )

    else:

        ci_t = (
            energy.mean(),
            energy.mean()
        )

    # Bootstrap median CI
    if len(energy) > 1:

        ci_boot = bootstrap_ci_median(
            energy
        )

    else:

        ci_boot = (
            energy[0],
            energy[0]
        )

    mean_energy = float(
        energy.mean()
    )

    std_energy = float(
        energy.std(ddof=1)
        if len(energy) > 1
        else 0
    )

    # Coefficient of variation
    cv_percent = (
        100 * std_energy / mean_energy
        if mean_energy > 0
        else np.nan
    )

    result = {

        "median":
            float(np.median(energy)),

        "mean":
            mean_energy,

        "std":
            std_energy,

        "cv_percent":
            float(cv_percent),

        "ci95_t_low":
            float(ci_t[0]),

        "ci95_t_high":
            float(ci_t[1]),

        "ci95_boot_low":
            float(ci_boot[0]),

        "ci95_boot_high":
            float(ci_boot[1]),

        "n":
            len(energy),

        "tokens_per_s_mean":
            float(
                clean[
                    "tokens_per_s"
                ].mean()
            ),

        "request_latency_mean_s":
            float(
                clean[
                    "request_latency_s"
                ].mean()
            ),

        "avg_power_mean_w":
            float(
                clean[
                    "avg_device_power_w"
                ].mean()
            ),

        "avg_gpu_utilization_mean_pct":
            float(
                clean[
                    "avg_gpu_utilization_pct"
                ].mean()
            ),

        "peak_memory_mean_mb":
            float(
                clean[
                    "peak_memory_mb"
                ].mean()
            ),

        "power_samples_mean":
            float(
                clean[
                    "n_power_samples"
                ].mean()
            ),
    }

    # PUE sensitivity
    for column in clean.columns:

        if column.startswith(
            "etok_total_facility_pue"
        ):

            result[
                f"{column}_mean"
            ] = float(
                clean[column].mean()
            )

    return result

