# # Energy-to-Token Production: Measurement Pipeline v7
#
# ## Research Methodology
#
# Primary metric:
#
#     End-to-End Energy per Output Token
#
#     E_tok = total GPU energy / number of generated output tokens
#
# We intentionally DO NOT estimate decode energy by subtracting
# a separate 1-token generation from a full generation.
#
# Previous validation showed that differential prefill/decode estimation
# was not reliable at this workload scale:
#
#     R² = 0.7372
#     regression slope = negative
#
# Therefore, this version measures the complete inference request:
#
#     Prefill + Decode
#            ↓
#     Total GPU Energy
#            ↓
#     Total Output Tokens
#            ↓
#     Joules / Output Token
#
# Research Question:
#
# How do quantization precision, batch size, and context length jointly
# affect energy efficiency (J/token), latency, throughput, memory,
# GPU utilization, and model quality during LLM inference?
#
# Main Hypothesis:
#
# Quantization does not necessarily reduce energy consumption per output
# token. Its effect depends on precision level, batch size, and context
# length, and may be limited or reversed by dequantization overhead or
# hardware/kernel inefficiencies.
#
# Experimental factors:
#
# Precision:
#     FP16
#     INT8
#     INT4
#
# Batch:
#     1
#     8
#
# Context:
#     128 tokens
#     2048 tokens
#
# Total configurations:
#
#     3 × 2 × 2 = 12
#
# Primary metric:
#
#     J/output-token
#
# Secondary metrics:
#
#     tokens/s
#     request latency
#     peak GPU memory
#     average GPU utilization
#     quality accuracy
#
# Energy is measured using NVML GPU power samples integrated
# using the trapezoidal rule.

