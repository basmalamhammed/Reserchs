MODEL_NAME = (
    "TinyLlama/TinyLlama-1.1B-Chat-v1.0"
)

MODEL_NUM_PARAMS = 1.1e9


def load_model(
    precision,
    attn_impl="eager",
):

    print(
        f"\nLoading model: "
        f"precision={precision}, "
        f"attention={attn_impl}"
    )

    tokenizer = AutoTokenizer.from_pretrained(
        MODEL_NAME,
        cache_dir=HF_CACHE,
    )

    if tokenizer.pad_token is None:

        tokenizer.pad_token = (
            tokenizer.eos_token
        )

    kwargs = {

        "device_map": "cuda",

        "attn_implementation":
            attn_impl,

    }

    # --------------------------------------------------------
    # FP16
    # --------------------------------------------------------

    if precision == "fp16":

        kwargs["dtype"] = torch.float16

    # --------------------------------------------------------
    # INT8
    # --------------------------------------------------------

    elif precision == "int8":

        kwargs[
            "quantization_config"
        ] = BitsAndBytesConfig(
            load_in_8bit=True
        )

    # --------------------------------------------------------
    # INT4
    # --------------------------------------------------------

    elif precision == "int4":

        kwargs[
            "quantization_config"
        ] = BitsAndBytesConfig(

            load_in_4bit=True,

            bnb_4bit_compute_dtype=
                torch.float16,

            bnb_4bit_quant_type=
                "nf4",
        )

    else:

        raise ValueError(
            f"Unknown precision: {precision}"
        )

    try:

        model = (
            AutoModelForCausalLM
            .from_pretrained(
                MODEL_NAME,
                cache_dir=HF_CACHE,
                **kwargs,
            )
        )

    except Exception as e:

        print(
            "*** Model loading failed "
            "with requested attention implementation. "
            "Falling back to eager. ***"
        )

        print("Error:", e)

        kwargs[
            "attn_implementation"
        ] = "eager"

        model = (
            AutoModelForCausalLM
            .from_pretrained(
                MODEL_NAME,
                cache_dir=HF_CACHE,
                **kwargs,
            )
        )

    model.eval()

    actual_impl = getattr(
        model.config,
        "_attn_implementation",
        "unknown"
    )

    print(
        "Actual attention implementation:",
        actual_impl
    )

    return model, tokenizer

