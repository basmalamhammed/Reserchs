CHECKPOINT_CSV = "etok_context_1792_final.csv"


def load_completed_configs(path):
    if not os.path.exists(path):
        return set()
    try:
        df = pd.read_csv(path)
        if "config" not in df.columns:
            return set()
        return set(df["config"].tolist())
    except Exception:
        return set()


def flatten_result_row(config_name, result):
    row = {
        "config": config_name,
        **result["summary"],
        "quality_accuracy": result["quality_accuracy"],
        "peak_memory_mb": result["peak_memory_mb"],
        "avg_gpu_utilization_pct": result["avg_gpu_utilization_pct"],
        "avg_request_latency_s": result["avg_request_latency_s"],
        "context_tokens": result["context_tokens"],
        "batch_size": result["batch_size"],
        "precision": result["precision"],
    }
    for tier, diagnostic in result["diagnostics"].items():
        row.update({f"{tier}_{key}": value for key, value in diagnostic.items()})
    return row


def append_checkpoint(config_name, result, path=CHECKPOINT_CSV):
    if os.path.exists(path):
        existing = pd.read_csv(path)
    else:
        existing = pd.DataFrame()

    new_row = pd.DataFrame([flatten_result_row(config_name, result)])

    if len(existing):
        existing = existing[existing["config"] != config_name]
        combined = pd.concat([existing, new_row], ignore_index=True)
    else:
        combined = new_row

    combined.to_csv(path, index=False)
    print(f"[checkpoint] {config_name} saved -> {path} ({len(combined)} configs)")


def run_experiment_sweep(
    precisions=("fp16", "int8", "int4"),
    batch_sizes=(1, 8),
    attn_impls=("eager",),
    context_lengths=CONTEXT_LENGTHS,
    n_repeats=8,
    max_new_tokens=100,
    pue_estimate=1.10,
    num_params=MODEL_NUM_PARAMS,
    quality_subset=None,
    checkpoint_path=CHECKPOINT_CSV,
):
    if quality_subset is None:
        quality_subset = MMLU_SMOKE_SUBSET
        print("*** WARNING: Using 3-question smoke test. "
              "Use 100 questions for the real experiment. ***")

    completed = load_completed_configs(checkpoint_path)
    if completed:
        print(f"Resuming: {len(completed)} configuration(s) already done.")

    all_results = {}

    # ========================================================
    # Precision × Attention
    # ========================================================
    for precision, attn_impl in itertools.product(precisions, attn_impls):

        print("\n" + "=" * 70)
        print(f"MODEL: precision={precision}, attention={attn_impl}")
        print("=" * 70)

        model, tokenizer = load_model(precision, attn_impl)

        microbench_keff = measure_microbench_keff(dtype=torch.float16)
        print(f"Microbenchmark Keff: {microbench_keff / 1e12:.2f} TFLOPs/s")

        quality = evaluate_quality(model, tokenizer, quality_subset)
        print(f"Quality accuracy: {quality:.2%} (n={len(quality_subset)})")

        # ====================================================
        # Batch × Context
        # ====================================================
        for batch_size, (ctx_name, ctx_len) in itertools.product(batch_sizes, context_lengths.items()):

            config_name = f"{precision}_{attn_impl}_batch{batch_size}_{ctx_name}"

            if config_name in completed:
                print(f"\nSKIPPING: {config_name}")
                continue

            print("\n" + "-" * 70)
            print(f"CONFIG: {config_name}")
            print("-" * 70)

            input_ids = build_exact_length_input_ids(tokenizer, ctx_len, model.device)
            print("Input context tokens:", input_ids.shape[1])

            # ------------------------------------------------
            # Reduce max_new_tokens for large batch + long
            # context, to lower OOM risk before we even try.
            # ------------------------------------------------
            effective_max_new_tokens = max_new_tokens
            if batch_size >= 8 and ctx_len >= 1000:
                effective_max_new_tokens = 30
                print(f"  (reduced max_new_tokens to {effective_max_new_tokens} "
                      f"for large batch+context)")

            # ------------------------------------------------
            # Measurements -- OOM-safe: log and skip, don't crash
            # ------------------------------------------------
            try:
                raw_df = run_with_repeats(
                    model, tokenizer, input_ids, config_name,
                    n_repeats=n_repeats, max_new_tokens=effective_max_new_tokens,
                    batch_size=batch_size, pue=pue_estimate,
                )
            except torch.cuda.OutOfMemoryError:
                print(f"  *** OOM on {config_name} (batch={batch_size}, ctx={ctx_len}) -- SKIPPING ***")
                torch.cuda.empty_cache()
                gc.collect()
                oom_log_entry = {
                    "config": config_name, "status": "OOM",
                    "batch_size": batch_size, "context_tokens": ctx_len, "precision": precision,
                }
                oom_path = "etok_oom_log.csv"
                existing_oom = pd.read_csv(oom_path) if os.path.exists(oom_path) else pd.DataFrame()
                pd.concat([existing_oom, pd.DataFrame([oom_log_entry])],
                          ignore_index=True).to_csv(oom_path, index=False)
                continue  # next config, sweep keeps going

            # ------------------------------------------------
            # Summary
            # ------------------------------------------------
            summary = summarize(raw_df)

            print("\nSummary:")
            print(f"Median J/token: {summary['median']:.4f}")
            print(f"Mean J/token: {summary['mean']:.4f}")
            print(f"CV: {summary['cv_percent']:.2f}%")
            print(f"Tokens/s: {summary['tokens_per_s_mean']:.2f}")
            print(f"Average power: {summary['avg_power_mean_w']:.2f} W")
            print(f"Average power samples: {summary['power_samples_mean']:.1f}")

            effective_throughput = effective_inference_throughput_proxy(
                2 * num_params, summary["tokens_per_s_mean"])

            avg_power = summary["avg_power_mean_w"]

            diagnostics = {
                "microbench": binding_constraint_diagnostic(
                    summary["median"], avg_power, int(num_params),
                    microbench_keff, "microbenchmark"),
                "effective_throughput_proxy": binding_constraint_diagnostic(
                    summary["median"], avg_power, int(num_params),
                    effective_throughput, "effective_throughput_proxy"),
            }

            peak_keff = PEAK_FLOPS_TABLE.get(gpu_name)
            if peak_keff:
                diagnostics["peak"] = binding_constraint_diagnostic(
                    summary["median"], avg_power, int(num_params), peak_keff, "peak")

            result_entry = {
                "raw_df": raw_df,
                "summary": summary,
                "quality_accuracy": quality,
                "peak_memory_mb": summary["peak_memory_mean_mb"],
                "avg_gpu_utilization_pct": summary["avg_gpu_utilization_mean_pct"],
                "avg_request_latency_s": summary["request_latency_mean_s"],
                "context_tokens": ctx_len,
                "batch_size": batch_size,
                "precision": precision,
                "diagnostics": diagnostics,
                "microbench_keff_flops_s": microbench_keff,
                "effective_throughput_proxy_flops_s": effective_throughput,
            }

            all_results[config_name] = result_entry

            append_checkpoint(config_name, result_entry, checkpoint_path)

        del model
        gc.collect()
        torch.cuda.empty_cache()
        print(f"\nFinished precision={precision}")

    return all_results

