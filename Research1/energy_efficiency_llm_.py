def binding_constraint_diagnostic(
    etok_j,
    avg_power_w,
    num_params,
    keff_flops_per_s,
    keff_label,
):

    ctok = (
        2 * num_params
    )

    rho = (
        avg_power_w
        / keff_flops_per_s
    )

    rho_star = (
        etok_j
        / ctok
    )

    constraint = (
        "Power-Limited"
        if rho < rho_star
        else "Compute-Limited"
    )

    return {

        "keff_type":
            keff_label,

        "ctok_flops_per_token":
            ctok,

        "rho_pj_per_flop":
            rho * 1e12,

        "rho_star_pj_per_flop":
            rho_star * 1e12,

        "constraint":
            constraint,
    }

