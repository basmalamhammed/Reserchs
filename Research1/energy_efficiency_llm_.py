def build_exact_length_input_ids(
    tokenizer,
    target_len,
    model_device,
    filler_text=(
        "The quick brown fox jumps over the lazy dog. "
    ),
):

    instruction = (
        " Given all of the above, explain the concept "
        "of gradient descent in machine learning."
    )

    instr_ids = tokenizer(
        instruction,
        return_tensors="pt"
    )["input_ids"]

    instr_len = instr_ids.shape[1]

    filler_ids = tokenizer(
        filler_text,
        return_tensors="pt"
    )["input_ids"][0]

    needed = target_len - instr_len

    if needed <= 0:

        raise ValueError(
            f"target_len={target_len} is too short."
        )

    repetitions = (
        needed // filler_ids.shape[0]
    ) + 1

    filler_repeated = (
        filler_ids
        .repeat(repetitions)
        [:needed]
    )

    full_ids = torch.cat(
        [
            filler_repeated,
            instr_ids[0],
        ]
    ).unsqueeze(0)

    full_ids = full_ids.to(
        model_device
    )

    assert full_ids.shape[1] == target_len

    return full_ids


