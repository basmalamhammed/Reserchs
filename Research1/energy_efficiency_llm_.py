def feasibility_analysis(

    summary_df,

    baseline_config,

    quality_epsilon=0.02,

    latency_slo_s=None,
):

    base = summary_df[
        summary_df["config"]
        == baseline_config
    ]

    if len(base) == 0:

        print(
            f"Baseline not found: "
            f"{baseline_config}"
        )

        return pd.DataFrame()

    baseline_quality = (
        base.iloc[0][
            "quality_accuracy"
        ]
    )

    rows = []

    for _, row in summary_df.iterrows():

        quality_ok = (
            row["quality_accuracy"]
            >=
            baseline_quality
            - quality_epsilon
        )

        if latency_slo_s is None:

            latency_ok = True

        else:

            latency_ok = (
                row[
                    "avg_request_latency_s"
                ]
                <= latency_slo_s
            )

        rows.append({

            "config":
                row["config"],

            "energy_j_per_token":
                row["median"],

            "quality_accuracy":
                row["quality_accuracy"],

            "latency_s":
                row[
                    "avg_request_latency_s"
                ],

            "quality_feasible":
                quality_ok,

            "latency_feasible":
                latency_ok,

            "feasible":
                quality_ok
                and latency_ok,
        })

    result = pd.DataFrame(
        rows
    ).sort_values(
        "energy_j_per_token"
    )

    feasible = result[
        result["feasible"]
    ]

    if len(feasible):

        best = feasible.iloc[0]

        print(
            "\nBest feasible configuration:"
        )

        print(
            best["config"]
        )

        print(
            f"Energy: "
            f"{best['energy_j_per_token']:.4f} J/token"
        )

        print(
            f"Quality: "
            f"{best['quality_accuracy']:.2%}"
        )

    else:

        print(
            "No configuration meets "
            "the feasibility constraints."
        )

    return result

