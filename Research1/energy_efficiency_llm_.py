LETTER_LABELS = ["A", "B", "C", "D"]


def format_mmlu_prompt(item):

    lines = [
        item["question"]
    ]

    for label, choice in zip(
        LETTER_LABELS,
        item["choices"]
    ):
        lines.append(
            f"{label}. {choice}"
        )

    lines.append("Answer:")

    return "\n".join(lines)


def evaluate_quality(
    model,
    tokenizer,
    subset,
):

    model.eval()

    letter_ids = []

    for letter in LETTER_LABELS:

        ids = tokenizer(
            " " + letter,
            add_special_tokens=False
        )["input_ids"]

        if len(ids) != 1:

            raise ValueError(
                f"Letter {letter} is not a single token: {ids}"
            )

        letter_ids.append(
            ids[0]
        )

    correct = 0

    for item in subset:

        prompt = format_mmlu_prompt(item)

        encoded = tokenizer(
            prompt,
            return_tensors="pt"
        )

        ids = encoded["input_ids"].to(
            model.device
        )

        with torch.no_grad():

            outputs = model(
                input_ids=ids
            )

        logits = outputs.logits[
            0,
            -1,
            :
        ]

        choice_logits = [
            logits[token_id].item()
            for token_id in letter_ids
        ]

        prediction = int(
            np.argmax(choice_logits)
        )

        correct += int(
            prediction == item["answer"]
        )

    return correct / len(subset)

