def check_pue_ranking_robustness(
    summary_df
):

    rankings = {}

    for p in PUE_SWEEP:

        column = (
            f"etok_total_facility_pue"
            f"{p}_mean"
        )

        if column not in summary_df.columns:

            print(
                f"Missing PUE column: {column}"
            )

            continue

        rankings[p] = list(
            summary_df
            .sort_values(column)
            ["config"]
        )

    if not rankings:

        print(
            "No PUE results available."
        )

        return None, {}

    base = rankings[
        list(rankings.keys())[0]
    ]

    stable = all(
        rankings[p] == base
        for p in rankings
    )

    print(
        "PUE ranking stable:",
        stable
    )

    if not stable:

        print(
            "*** WARNING: Configuration "
            "ranking changes with PUE assumption. "
            "Report this explicitly. ***"
        )

    return stable, rankings

