# Cell 10b: Microbenchmark Effective Throughput
# ============================================================

def measure_microbench_keff(
    dtype=torch.float16,
    matrix_size=2048,
    n_repeats=10,
):
    """
    Simple GPU GEMM microbenchmark.

    This measures an empirical compute-throughput proxy
    for the current GPU.

    It is NOT the model's inference throughput.
    """

    if not torch.cuda.is_available():

        raise RuntimeError(
            "CUDA GPU is required for the microbenchmark."
        )

    device = torch.device("cuda")

    A = torch.randn(
        matrix_size,
        matrix_size,
        device=device,
        dtype=dtype,
    )

    B = torch.randn(
        matrix_size,
        matrix_size,
        device=device,
        dtype=dtype,
    )

    # Warmup
    for _ in range(3):

        _ = torch.matmul(A, B)

    torch.cuda.synchronize()

    times = []

    for _ in range(n_repeats):

        start = torch.cuda.Event(
            enable_timing=True
        )

        end = torch.cuda.Event(
            enable_timing=True
        )

        start.record()

        _ = torch.matmul(A, B)

        end.record()

        torch.cuda.synchronize()

        elapsed_ms = (
            start.elapsed_time(end)
        )

        times.append(
            elapsed_ms / 1000.0
        )

    median_time_s = float(
        np.median(times)
    )

    # GEMM FLOPs ≈ 2 * N^3
    flops = (
        2
        * matrix_size
        * matrix_size
        * matrix_size
    )

    keff = (
        flops
        / median_time_s
    )

    del A, B

    torch.cuda.empty_cache()

    return float(keff)

