class SystemMonitor:
    """
    Samples GPU power and utilization during one workload.

    Energy is estimated using trapezoidal integration:

        E = integral Power(t) dt

    Sampling interval:
        5 ms
    """

    def __init__(
        self,
        handle,
        pue: float = 1.10,
        sample_interval_s: float = 0.005,
    ):
        self.handle = handle
        self.pue = pue
        self.sample_interval_s = sample_interval_s

        self._power_samples = []
        self._util_samples = []

        self._stop_event = threading.Event()
        self._thread = None

    def _sample_loop(self):

        while not self._stop_event.is_set():

            t = time.perf_counter()

            try:

                power_w = (
                    nvmlDeviceGetPowerUsage(
                        self.handle
                    ) / 1000.0
                )

                utilization = (
                    nvmlDeviceGetUtilizationRates(
                        self.handle
                    ).gpu
                )

                self._power_samples.append(
                    (t, power_w)
                )

                self._util_samples.append(
                    utilization
                )

            except Exception:
                pass

            time.sleep(
                self.sample_interval_s
            )

    def __enter__(self):

        self._power_samples = []
        self._util_samples = []

        self._stop_event.clear()

        self._thread = threading.Thread(
            target=self._sample_loop,
            daemon=True,
        )

        self._thread.start()

        # Give sampler a tiny head start.
        time.sleep(
            self.sample_interval_s * 2
        )

        return self

    def __exit__(
        self,
        exc_type,
        exc_val,
        exc_tb,
    ):

        self._stop_event.set()

        if self._thread is not None:

            self._thread.join(
                timeout=2.0
            )

    def results(self):

        n_samples = len(
            self._power_samples
        )

        if n_samples < 3:

            raise RuntimeError(
                f"Only {n_samples} GPU power samples collected. "
                f"Increase max_new_tokens or reduce "
                f"sample_interval_s."
            )

        ts = np.array(
            [
                x[0]
                for x in self._power_samples
            ],
            dtype=float,
        )

        ws = np.array(
            [
                x[1]
                for x in self._power_samples
            ],
            dtype=float,
        )

        device_joules = float(
            np.trapezoid(
                ws,
                ts,
            )
        )

        duration_s = float(
            ts[-1] - ts[0]
        )

        avg_power = float(
            ws.mean()
        )

        avg_util = float(
            np.mean(
                self._util_samples
            )
        )

        return {
            "device_joules":
                device_joules,

            "facility_joules_estimate":
                device_joules * self.pue,

            "avg_device_power_w":
                avg_power,

            "avg_gpu_utilization_pct":
                avg_util,

            "duration_s":
                duration_s,

            "n_samples":
                n_samples,
        }



